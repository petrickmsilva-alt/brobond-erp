// Explicit MRP action on operational demand. It creates official planned OPs.
import type { Request, Response } from 'express';
import { currentUser } from './auth';
import { escopoDoAtor, assertRegistroDaEmpresa } from './empresa';
import { checkAccess, getStore } from './services';
import { getResource } from './resources';
import { HttpError } from './errors';
import { parseId } from './validate';
import { listarTodos } from './paginacaoCompleta';
import { itensProducao, validarOrdemPayload, fichaDoProduto } from './producao';

export async function planejarDemanda(req: Request, res: Response) {
  const actor = currentUser(req); const r = getResource('ordens')!; checkAccess(r, actor, 'create');
  if (!['admin', 'gerente'].includes(actor.perfil)) throw new HttpError(403, 'Planejamento exige gerente ou administrador.');
  const scope = escopoDoAtor(actor); const saleId = parseId(String(req.body?.venda_id)); const s = getStore();
  const result = await s.transaction(async (tx) => {
    // Serialize planning across all demand in the company, not only this sale.
    if (tx) await tx.query('SELECT pg_advisory_xact_lock(73109,$1)', [scope.empresaId]);
    const sale = assertRegistroDaEmpresa(getResource('vendas')!, await s.get(getResource('vendas')!, saleId, tx), scope);
    if (!['aberta', 'cotacao'].includes(String(sale.status))) throw new HttpError(409, 'Planeje somente demanda aberta.');
    const items = await listarTodos(getResource('itens_venda')!, { empresa_id: scope.empresaId, venda_id: saleId }, tx);
    if (!items.length) throw new HttpError(409, 'Demanda sem itens.');
    const orders = await listarTodos(r, { empresa_id: scope.empresaId }, tx);
    const supply = new Map<string, number>();
    for (const stock of await listarTodos(getResource('estoques')!, { empresa_id: scope.empresaId }, tx)) {
      const key = `${stock.produto_id}:${stock.tamanho_id}`; supply.set(key, (supply.get(key) || 0) + Number(stock.quantidade));
    }
    for (const reserve of await listarTodos(getResource('estoque_reservas')!, { empresa_id: scope.empresaId }, tx)) {
      if (reserve.status !== 'ativa' || (reserve.expira_em && new Date(reserve.expira_em).getTime() <= Date.now())) continue;
      const key = `${reserve.produto_id}:${reserve.tamanho_id}`; supply.set(key, (supply.get(key) || 0) - Number(reserve.quantidade));
    }
    // Existing production covers demand, including OPs not generated by this endpoint.
    for (const op of orders) if (!op.demanda_item_id && ['planejada', 'liberada', 'em_producao', 'parcial'].includes(String(op.status))) {
      const progress = await listarTodos(getResource('ordens_apontamentos')!, { empresa_id: scope.empresaId, ordem_id: Number(op.id) }, tx);
      for (const item of await itensProducao(op, scope, tx)) {
        const processed = op.tipo === 'grade'
          ? progress.filter((p) => Number(p.tamanho_id) === item.tamanho_id).reduce((n, p) => n + Number(p.quantidade_produzida || 0) + Number(p.quantidade_perdida || 0), 0)
          : Number(op.quantidade_produzida || 0) + Number(op.quantidade_perdida || 0);
        const key = `${op.produto_id}:${item.tamanho_id}`; supply.set(key, (supply.get(key) || 0) + Math.max(0, item.quantidade - processed));
      }
    }
    const sales = await listarTodos(getResource('vendas')!, { empresa_id: scope.empresaId }, tx);
    const openIds = new Set(sales.filter((v) => ['aberta', 'cotacao'].includes(String(v.status))).map((v) => Number(v.id)));
    const demand = (await listarTodos(getResource('itens_venda')!, { empresa_id: scope.empresaId }, tx))
      .filter((item) => openIds.has(Number(item.venda_id))).sort((a, b) => Number(a.id) - Number(b.id));
    const planned = [];
    for (const item of demand) {
      const old = orders.find((op) => Number(op.demanda_item_id) === Number(item.id) && op.status !== 'cancelada');
      if (old) {
        // A demand-linked OP covers only its unfinished production. Its share
        // of physical stock still belongs to this demand, not the next sale.
        const key = `${item.produto_id}:${item.tamanho_id}`;
        const outstanding = ['planejada', 'liberada', 'em_producao', 'parcial'].includes(String(old.status))
          ? Math.max(0, Number(old.quantidade) - Number(old.quantidade_produzida || 0) - Number(old.quantidade_perdida || 0)) : 0;
        const available = Math.max(0, supply.get(key) || 0);
        const requiredStock = Math.max(0, Number(item.quantidade) - outstanding);
        supply.set(key, Math.max(0, available - requiredStock));
        if (Number(item.venda_id) === saleId) {
          if (available < requiredStock) throw new HttpError(409, 'Demanda alterada ou perda de produção: revise a OP vinculada antes de replanejar.');
          planned.push(old);
        }
        continue;
      }
      const key = `${item.produto_id}:${item.tamanho_id}`;
      const available = Math.max(0, supply.get(key) || 0);
      const missing = Math.max(0, Number(item.quantidade) - available);
      supply.set(key, Math.max(0, available - Number(item.quantidade)));
      if (!missing || Number(item.venda_id) !== saleId) continue;
      if (!await fichaDoProduto(Number(item.produto_id), scope, tx)) throw new HttpError(409, 'Produto sem ficha técnica não pode gerar OP pelo MRP.');
      const data = { empresa_id: scope.empresaId, produto_id: item.produto_id, tamanho_id: item.tamanho_id, tipo: 'tamanho', quantidade: missing,
        status: 'planejada', demanda_item_id: item.id, previsao: sale.previsao_entrega || null };
      await validarOrdemPayload(data, null);
      const op = await s.insert(r, data, tx); planned.push(op);
      await s.audit({ empresa_id: scope.empresaId, usuario_id: actor.id, usuario: actor.name, acao: 'criar', recurso: r.key,
        registro_id: Number(op.id), descricao: `MRP: OP planejada para item de demanda #${item.id}`, dados: { venda_id: saleId, quantidade: missing } }, tx);
    }
    return { ordens: planned };
  }, { isolation: 'read committed' }); res.json(result);
}
